function semanticTokenColors(p) {
  const s = p.syntax;
  return {
    namespace: s.namespace,
    type: s.type,
    class: s.type,
    enum: s.type,
    interface: s.type,
    struct: s.type,
    typeParameter: { foreground: s.type, italic: true },
    parameter: { foreground: s.param, italic: true },
    variable: s.variable,
    'variable.readonly': s.constant,
    'variable.defaultLibrary': s.type,
    property: s.property,
    'property.readonly': s.property,
    enumMember: s.constant,
    function: s.func,
    method: s.func,
    macro: s.decorator,
    decorator: { foreground: s.decorator, italic: true },
    keyword: s.keyword,
    number: s.number,
    regexp: s.regex,
    string: s.string,
    selfKeyword: { foreground: s.keyword, italic: true },
    '*.deprecated': { strikethrough: true },
  };
}

function buildTheme(collection, variant, displayName) {
  const p = variant.palette;
  const dark = variant.type === 'dark';
  return {
    $schema: 'vscode://schemas/color-theme',
    name: displayName,
    type: variant.type,
    semanticHighlighting: true,
    colors: workbenchColors(p, dark),
    tokenColors: tokenColors(p),
    semanticTokenColors: semanticTokenColors(p),
  };
}

module.exports = { buildTheme };
